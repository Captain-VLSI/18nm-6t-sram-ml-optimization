#!/usr/bin/env python3
"""
6T SRAM Leakage Current & Power Sweep
Generates the OCEAN sweep script, runs it, and reads the CSV.
Run this on the Linux machine where Cadence is installed.
"""
import os
import subprocess
import sys

# ============================================================
# USER-CONFIGURABLE PARAMETERS
# ============================================================
PU_RANGE  = [1, 2, 3, 4, 5]
PD_RANGE  = [1, 2, 3, 4, 5, 6]
ACC_RANGE = [1, 2, 3, 4, 5]
VDD_RANGE = [0.6, 0.7, 0.8, 0.9]

SIM_DIR   = "/home/vlsi-lab/simulation/6tsram_tran_tb/spectre/schematic"
CSV_PATH  = "/home/vlsi-lab/simulation/sram_leakage_dataset.csv"
OCN_PATH  = "/home/vlsi-lab/simulation/leakage_sweep_auto.ocn"

MODEL_PATH = "/home/install/FOUNDRY/cds_ff_mpt_v_0.5/cds_ff_mpt/../models/spectre/cds_ff_mpt.scs"
MODEL_SEC  = "tt"
TEMP       = 27
# ============================================================

TOTAL_RUNS = len(PU_RANGE) * len(PD_RANGE) * len(ACC_RANGE) * len(VDD_RANGE)


def generate_ocean_script():
    """Generate the complete OCEAN leakage sweep script."""
    nf_param = f'{SIM_DIR}/netlist/netlist_leakage'
    pu_list  = " ".join(str(x) for x in PU_RANGE)
    pd_list  = " ".join(str(x) for x in PD_RANGE)
    acc_list = " ".join(str(x) for x in ACC_RANGE)
    vdd_list = " ".join(str(x) for x in VDD_RANGE)

    script = f'''; AUTO-GENERATED by run_leakage_sweep.py
; 6T SRAM Leakage Sweep ({TOTAL_RUNS} simulations)
; Standby mode: WL=0, BL=BLB=VDD

simdir   = "{SIM_DIR}"
nf_param = "{nf_param}"
csvpath  = "{CSV_PATH}"

printf("=== SRAM LEAKAGE Sweep ({TOTAL_RUNS} runs) ===\\n")

sh(sprintf(nil "mkdir -p %s/netlist" simdir))
sh(sprintf(nil "mkdir -p %s/psf" simdir))

; --- Procedure: write standby leakage netlist ---
procedure( write_leakage_netlist(pu pd acc vdd nf_path)
  let((of)
    of = outfile(nf_path "w")
    fprintf(of "// 6T SRAM Leakage - PU=%d PD=%d ACC=%d VDD=%.2f\\n" pu pd acc vdd)
    fprintf(of "simulator lang=spectre\\n")
    fprintf(of "global 0\\n")
    fprintf(of "include \\"{MODEL_PATH}\\" section={MODEL_SEC}\\n")
    fprintf(of "\\n")
    fprintf(of "subckt sram6t bl blb gnd_pin q qb vdc w\\n")
    fprintf(of "    NM0 (qb q gnd_pin gnd_pin) cds_ff_mpt_n1svt l=18.0n nfin=%d nf=1 m=1 ngcon=1 \\\\\\n" pd)
    fprintf(of "        asej=6.528e-15 adej=6.528e-15 psej=2.32e-07 pdej=2.32e-07 lrsd=68.0n\\n")
    fprintf(of "    NM1 (q qb gnd_pin gnd_pin) cds_ff_mpt_n1svt l=18.0n nfin=%d nf=1 m=1 ngcon=1 \\\\\\n" pd)
    fprintf(of "        asej=6.528e-15 adej=6.528e-15 psej=2.32e-07 pdej=2.32e-07 lrsd=68.0n\\n")
    fprintf(of "    NM2 (blb w qb gnd_pin) cds_ff_mpt_n1svt l=18.0n nfin=%d nf=1 m=1 ngcon=1 \\\\\\n" acc)
    fprintf(of "        asej=3.264e-15 adej=3.264e-15 psej=1.84e-07 pdej=1.84e-07 lrsd=68.0n\\n")
    fprintf(of "    NM3 (bl w q gnd_pin) cds_ff_mpt_n1svt l=18.0n nfin=%d nf=1 m=1 ngcon=1 \\\\\\n" acc)
    fprintf(of "        asej=3.264e-15 adej=3.264e-15 psej=1.84e-07 pdej=1.84e-07 lrsd=68.0n\\n")
    fprintf(of "    PM0 (qb q vdc vdc) cds_ff_mpt_p1svt l=18.0n nfin=%d nf=1 m=1 ngcon=1 \\\\\\n" pu)
    fprintf(of "        asej=3.264e-15 adej=3.264e-15 psej=1.84e-07 pdej=1.84e-07 lrsd=68.0n\\n")
    fprintf(of "    PM1 (q qb vdc vdc) cds_ff_mpt_p1svt l=18.0n nfin=%d nf=1 m=1 ngcon=1 \\\\\\n" pu)
    fprintf(of "        asej=3.264e-15 adej=3.264e-15 psej=1.84e-07 pdej=1.84e-07 lrsd=68.0n\\n")
    fprintf(of "ends sram6t\\n")
    fprintf(of "\\n")
    fprintf(of "I0 (bl blb 0 q qb net6 w) sram6t\\n")
    fprintf(of "V_BL  (bl 0)   vsource dc=%.2f type=dc\\n" vdd)
    fprintf(of "V_BLB (blb 0)  vsource dc=%.2f type=dc\\n" vdd)
    fprintf(of "V_WL  (w 0)    vsource dc=0 type=dc\\n")
    fprintf(of "V_VDD (net6 0) vsource dc=%.2f type=dc\\n" vdd)
    fprintf(of "ic q=%.2f qb=0\\n" vdd)
    fprintf(of "save V_VDD:p\\n")
    fprintf(of "simulatorOptions options reltol=1e-3 vabstol=1e-6 iabstol=1e-12 temp={TEMP} tnom={TEMP} gmin=1e-12 rforce=1 maxnotes=5 maxwarns=5 save=allpub currents=all\\n")
    close(of)
  )
)

; --- Debug run ---
printf("\\n=== DEBUG RUN ===\\n")
write_leakage_netlist({PU_RANGE[0]} {PD_RANGE[0]} {ACC_RANGE[0]} {VDD_RANGE[-1]} nf_param)
simulator('spectre)
design(nf_param)
resultsDir(simdir)
modelFile('("{MODEL_PATH}" "{MODEL_SEC}"))
analysis('tran ?stop "5n" ?errpreset "moderate")
envOption('analysisOrder list("tran"))
temp({TEMP})

printf("Running debug simulation...\\n")
dbg_ok = errset(run())
vdd_current_name = nil

if( dbg_ok then
    errset(selectResult('tran))
    printf("Debug sim OK!\\n")
    cond(
        (errset(i("/V_VDD"))        vdd_current_name = "/V_VDD")
        (errset(i("/V_VDD:p"))      vdd_current_name = "/V_VDD:p")
        (errset(i("/V_VDD:plus"))   vdd_current_name = "/V_VDD:plus")
        (errset(i("/V_VDD/plus"))   vdd_current_name = "/V_VDD/plus")
        (errset(i("/V_VDD/PLUS"))   vdd_current_name = "/V_VDD/PLUS")
        (errset(i("/V_VDD/p"))      vdd_current_name = "/V_VDD/p")
    )
    if( vdd_current_name then
        printf("  OK: VDD current = %s\\n" vdd_current_name)
        ilk_test = errset(value(i(vdd_current_name) 4e-9))
        if( ilk_test then
            printf("  Test leakage: %e A (%.4f nA)\\n" car(ilk_test) abs(car(ilk_test))*1e9)
        )
    else
        printf("  FAIL: VDD current not found\\n")
        printf("  TIP: In CIW run selectResult('tran) then getData()\\n")
    )
else
    printf("Debug FAILED!\\n")
)
printf("=== END DEBUG ===\\n\\n")

; --- Sweep ---
puL  = '({pu_list})
pdL  = '({pd_list})
accL = '({acc_list})
vddL = '({vdd_list})

printf("Opening CSV: %s\\n" csvpath)
ofile = outfile(csvpath "w")
if( ofile then printf("CSV opened OK\\n") else printf("ERROR: Cannot open CSV!\\n"))
fprintf(ofile "nfin_pu,nfin_pd,nfin_acc,vdd,leakage_current_nA,leakage_power_nW\\n")

cnt = 0

foreach( pu puL
  foreach( pd pdL
    foreach( acc accL
      foreach( vdd vddL

        cnt = cnt + 1
        printf("Run %d/{TOTAL_RUNS}: PU=%d PD=%d ACC=%d VDD=%.2f\\n" cnt pu pd acc vdd)

        write_leakage_netlist(pu pd acc vdd nf_param)
        design(nf_param)
        resultsDir(simdir)
        analysis('tran ?stop "5n" ?errpreset "moderate")
        temp({TEMP})

        ilk = -1.0
        plk = -1.0

        sok = errset(run())
        if( sok then
            rok = errset(selectResult('tran))
            if( rok then
                if( vdd_current_name then
                    ilk_raw = errset(value(i(vdd_current_name) 4e-9))
                    if( ilk_raw then
                        ilk_val = car(ilk_raw)
                        if( numberp(ilk_val) then
                            ilk = abs(ilk_val) * 1e9
                            plk = ilk * vdd
                        )
                    )
                )
            )
        )

        fprintf(ofile "%d,%d,%d,%.2f,%.4f,%.4f\\n" pu pd acc vdd ilk plk)
        printf("  Ileak=%.4f nA  Pleak=%.4f nW\\n" ilk plk)

      )
    )
  )
)

close(ofile)
printf("\\n=== LEAKAGE SWEEP DONE (%d runs) ===\\n" cnt)
printf("Saved: %s\\n" csvpath)
'''
    return script


def main():
    print(f"=== SRAM Leakage Sweep Generator ===")
    print(f"Total simulations: {TOTAL_RUNS}")
    print(f"Sweep: PU={PU_RANGE}, PD={PD_RANGE}, ACC={ACC_RANGE}, VDD={VDD_RANGE}")
    print()

    ocn_script = generate_ocean_script()
    with open(OCN_PATH, 'w') as f:
        f.write(ocn_script)
    print(f"OCEAN script written to: {OCN_PATH}")

    if "--run" in sys.argv:
        print(f"\nLaunching OCEAN...")
        result = subprocess.run(
            ["ocean", "-restore", OCN_PATH],
            cwd=os.path.dirname(OCN_PATH),
            timeout=3600
        )
        if result.returncode == 0:
            print(f"\nDone! CSV saved at: {CSV_PATH}")
        else:
            print(f"\nOCEAN exited with code {result.returncode}")
    else:
        print(f"\nTo run the simulation, either:")
        print(f"  python3 {os.path.basename(__file__)} --run")
        print(f"  OR in Virtuoso CIW:")
        print(f'  load("{OCN_PATH}")')

    if os.path.exists(CSV_PATH):
        import csv as csvmod
        with open(CSV_PATH) as f:
            rows = list(csvmod.DictReader(f))
        print(f"\nCSV has {len(rows)} rows")
        valid = sum(1 for r in rows if float(r['leakage_current_nA']) > 0)
        print(f"Valid leakage values: {valid}/{len(rows)}")


if __name__ == "__main__":
    main()
