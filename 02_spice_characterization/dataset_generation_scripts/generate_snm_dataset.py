def parse_val(s):
    s = s.strip()
    multipliers = {'f': 1e-15, 'p': 1e-12, 'n': 1e-9, 'u': 1e-6, 'm': 1e-3, 'k': 1e3, 'M': 1e6, 'G': 1e9}
    if s and s[-1] in multipliers:
        return float(s[:-1]) * multipliers[s[-1]]
    return float(s)

def read_vtc_file(filepath):
    """ Reads 2-column VTC file generated by Cadence ocnPrint """
    if not os.path.exists(filepath):
        return [], []
    vq = []
    vqb = []
    with open(filepath, 'r') as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) >= 2:
                try:
                    x = parse_val(parts[0])
                    y = parse_val(parts[1])
                    vq.append(x)
                    vqb.append(y)
                except ValueError:
                    continue
    return vq, vqb

def maximum_square_in_lobe(poly_x, poly_y, grid_res=300):
    """
    Numerical maximum-inscribed-square search in 45-degree rotated coordinates.
    Computes upper and lower envelope profiles by intersecting all polygon edges
    across the rotated u-axis and searches for the largest enclosed square.
    """
    if len(poly_x) < 10:
        return 0.0

    root2 = np.sqrt(2.0)
    # Rotate polygon vertices to (u, v) coordinates: u = (x + y)/sqrt(2), v = (y - x)/sqrt(2)
    u_pts = (poly_x + poly_y) / root2
    v_pts = (poly_y - poly_x) / root2

    u_min = np.min(u_pts)
    u_max = np.max(u_pts)
    
    if u_max - u_min < 1e-5:
        return 0.0

    # Ensure polygon is closed
    if u_pts[0] != u_pts[-1] or v_pts[0] != v_pts[-1]:
        u_pts = np.append(u_pts, u_pts[0])
        v_pts = np.append(v_pts, v_pts[0])

    n_edges = len(u_pts) - 1
    u_grid = np.linspace(u_min, u_max, grid_res)

    v_top = np.full(grid_res, -np.inf)
    v_bot = np.full(grid_res, np.inf)

    # Intersect all polygon edges across the u_grid
    for j in range(n_edges):
        u1, u2 = u_pts[j], u_pts[j+1]
        v1, v2 = v_pts[j], v_pts[j+1]

        u_start, u_end = min(u1, u2), max(u1, u2)
        if u_end - u_start < 1e-12:
            continue

        mask = (u_grid >= u_start) & (u_grid <= u_end)
        if not np.any(mask):
            continue

        u_sub = u_grid[mask]
        # Linear interpolation of edge v at u_sub
        v_interp = v1 + (u_sub - u1) * (v2 - v1) / (u2 - u1)

        v_top[mask] = np.maximum(v_top[mask], v_interp)
        v_bot[mask] = np.minimum(v_bot[mask], v_interp)

    valid_mask = (v_top != -np.inf) & (v_bot != np.inf) & (v_top > v_bot)
    if not np.any(valid_mask):
        return 0.0

    upper_env = np.where(valid_mask, v_top, 0.0)
    lower_env = np.where(valid_mask, v_bot, 0.0)
    height_env = upper_env - lower_env

    max_height = np.max(height_env)
    if max_height <= 0:
        return 0.0

    # Binary search for maximum square side S
    def can_fit_square(S):
        if S <= 0:
            return True
        half = S / 2.0
        du = u_grid[1] - u_grid[0]
        half_idx = int(np.ceil(half / du))

        # Check candidate centers
        for c_idx in range(half_idx, len(u_grid) - half_idx):
            start_idx = c_idx - half_idx
            end_idx = c_idx + half_idx + 1

            if not np.all(valid_mask[start_idx:end_idx]):
                continue

            min_top = np.min(upper_env[start_idx:end_idx])
            max_bot = np.max(lower_env[start_idx:end_idx])

            if min_top - max_bot >= S:
                return True
        return False

    low = 0.0
    high = min(u_max - u_min, max_height)
    for _ in range(25):
        mid = 0.5 * (low + high)
        if can_fit_square(mid):
            low = mid
        else:
            high = mid

    return low

def calculate_snm_butterfly(sweep_v, vqb, sweep_step=0.005):
    """
    Geometric Seevinck SNM Extraction.
    1. Construct C1 = (Q, QB) and mirrored C2 = (QB, Q).
    2. Identify 3 principal intersections (left, center, right) using merge_tol = 1.5 * sweep_step.
    3. Verify closed lobe area for both left and right lobes.
    4. Search for maximum 45-degree axis-aligned square completely enclosed in each rotated (u, v) lobe.
    5. SNM = min(S_left, S_right) in mV. Returns 0.0 mV if butterfly is collapsed.
    """
    if len(sweep_v) < 20 or len(vqb) < 20:
        return 0.0

    x1 = np.asarray(sweep_v, dtype=float)
    y1 = np.asarray(vqb, dtype=float)

    valid = np.isfinite(x1) & np.isfinite(y1)
    x1, y1 = x1[valid], y1[valid]
    if len(x1) < 20:
        return 0.0

    # Clean C1
    order1 = np.argsort(x1)
    x1, y1 = x1[order1], y1[order1]
    k1 = np.ones(len(x1), dtype=bool)
    k1[1:] = np.diff(x1) > 1e-12
    x1, y1 = x1[k1], y1[k1]

    # Mirror C2
    x2, y2 = y1.copy(), x1.copy()
    order2 = np.argsort(x2)
    x2, y2 = x2[order2], y2[order2]
    k2 = np.ones(len(x2), dtype=bool)
    k2[1:] = np.diff(x2) > 1e-12
    x2, y2 = x2[k2], y2[k2]

    x_min = max(x1.min(), x2.min())
    x_max = min(x1.max(), x2.max())
    if x_max <= x_min:
        return 0.0

    # High-resolution grid
    x_grid = np.linspace(x_min, x_max, 2500)
    y1_grid = np.interp(x_grid, x1, y1)
    y2_grid = np.interp(x_grid, x2, y2)
    diff = y1_grid - y2_grid

    # Find roots
    roots = []
    zero_tol = max(1e-6, 0.001 * max(x_max - x_min, 1e-12))
    for i in range(len(x_grid)):
        if abs(diff[i]) < zero_tol:
            roots.append(x_grid[i])

    for i in range(len(x_grid) - 1):
        if diff[i] * diff[i+1] < 0:
            denom = diff[i+1] - diff[i]
            if abs(denom) > 1e-20:
                xr = x_grid[i] - diff[i] * (x_grid[i+1] - x_grid[i]) / denom
                roots.append(xr)

    if len(roots) == 0:
        return 0.0

    roots = np.sort(np.array(roots))
    merge_tol = 1.5 * sweep_step
    clustered = [roots[0]]
    for r in roots[1:]:
        if abs(r - clustered[-1]) > merge_tol:
            clustered.append(r)
        else:
            clustered[-1] = 0.5 * (clustered[-1] + r)

    intersections = np.array(clustered)
    intersections = intersections[(intersections >= x_min) & (intersections <= x_max)]

    if len(intersections) < 3:
        return 0.0

    left_root = intersections[0]
    right_root = intersections[-1]
    internal_roots = intersections[1:-1]

    if len(internal_roots) == 0:
        return 0.0

    center_target = 0.5 * (left_root + right_root)
    center_root = internal_roots[np.argmin(np.abs(internal_roots - center_target))]

    v_range = x_max - x_min
    if (center_root - left_root < 0.01 * v_range) or (right_root - center_root < 0.01 * v_range):
        return 0.0

    # Build Left Lobe Polygon
    left_grid = np.linspace(left_root, center_root, 300)
    left_y1 = np.interp(left_grid, x1, y1)
    left_y2 = np.interp(left_grid, x2, y2)
    left_poly_x = np.concatenate([left_grid, left_grid[::-1]])
    left_poly_y = np.concatenate([left_y1, left_y2[::-1]])

    # Build Right Lobe Polygon
    right_grid = np.linspace(center_root, right_root, 300)
    right_y1 = np.interp(right_grid, x1, y1)
    right_y2 = np.interp(right_grid, x2, y2)
    right_poly_x = np.concatenate([right_grid, right_grid[::-1]])
    right_poly_y = np.concatenate([right_y1, right_y2[::-1]])

    def polygon_area(px, py):
        return 0.5 * abs(np.sum(px[:-1] * py[1:] - px[1:] * py[:-1]))

    left_area = polygon_area(left_poly_x, left_poly_y)
    right_area = polygon_area(right_poly_x, right_poly_y)
    min_area = 1e-5 * v_range * v_range

    if left_area < min_area or right_area < min_area:
        return 0.0

    # Fast & exact 45-degree maximum square search in rotated (u, v) coordinates
    s_left = maximum_square_in_lobe(left_poly_x, left_poly_y)
    s_right = maximum_square_in_lobe(right_poly_x, right_poly_y)

    if s_left <= 1e-6 or s_right <= 1e-6:
        return 0.0

    snm_v = min(s_left, s_right)
    return round(snm_v * 1000.0, 2)

